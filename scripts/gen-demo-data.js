'use strict';
// Regenerates client/lib/demoData.js from the CURRENT database, so the no-backend
// static preview shows the SAME data as the live backend (real ActivityLog2 test data).
// Run after (re)seeding:  node scripts/gen-demo-data.js
const fs = require('fs');
const path = require('path');
const db = require('../server/db');

const MAX_RECS = 240; // downsample per activity to keep the bundle small

const r5 = (v) => (v == null ? null : +v.toFixed(5));
const r1 = (v) => (v == null ? null : +v.toFixed(1));

// Evenly downsample an array, always keeping the first and last element.
function downsample(arr, n) {
  if (arr.length <= n) return arr;
  const out = [];
  const step = (arr.length - 1) / (n - 1);
  for (let i = 0; i < n; i++) out.push(arr[Math.round(i * step)]);
  return out;
}

const activities = db.prepare('SELECT * FROM activities ORDER BY start_time ASC, id ASC').all();
const sports = db.prepare('SELECT DISTINCT sport FROM activities ORDER BY sport').all().map((r) => r.sport);
const equipment = db.prepare(`
  SELECT e.*, COUNT(ae.activity_id) AS activity_count
  FROM equipment e LEFT JOIN activity_equipment ae ON ae.equipment_id = e.id
  GROUP BY e.id ORDER BY e.last_seen DESC
`).all();

// Downsampled real records per activity id.
const recsBy = {};
const ins = db.prepare('SELECT t,lat,lon,altitude,speed,distance_m,hr,cadence,power,temperature FROM records WHERE activity_id=? ORDER BY t ASC, id ASC');
for (const a of activities) {
  const rows = ins.all(a.id).map((r) => ({
    t: r.t, lat: r5(r.lat), lon: r5(r.lon), altitude: r1(r.altitude), speed: r1(r.speed),
    distance_m: r.distance_m, hr: r.hr, cadence: r.cadence, power: r.power, temperature: r1(r.temperature),
  }));
  recsBy[a.id] = downsample(rows, MAX_RECS);
}

// Laps per activity id (kept whole — they're small and needed for the linked view).
const lapsBy = {};
const insLap = db.prepare(`
  SELECT idx, start_t, end_t, duration_s, start_distance_m, end_distance_m, distance_m,
         start_lat, start_lon, end_lat, end_lon, avg_speed, max_speed, avg_hr, max_hr,
         avg_power, max_power, elevation_gain, elevation_loss, avg_cadence, calories, lap_trigger
  FROM laps WHERE activity_id=? ORDER BY idx ASC
`);
for (const a of activities) {
  lapsBy[a.id] = insLap.all(a.id).map((l) => ({
    index: l.idx,
    start_t: l.start_t, end_t: l.end_t, duration_s: l.duration_s,
    start_distance_m: l.start_distance_m, end_distance_m: l.end_distance_m, distance_m: l.distance_m,
    start_lat: r5(l.start_lat), start_lon: r5(l.start_lon), end_lat: r5(l.end_lat), end_lon: r5(l.end_lon),
    avg_speed: r1(l.avg_speed), max_speed: r1(l.max_speed),
    avg_hr: l.avg_hr, max_hr: l.max_hr, avg_power: l.avg_power, max_power: l.max_power,
    elevation_gain: r1(l.elevation_gain), elevation_loss: r1(l.elevation_loss),
    avg_cadence: l.avg_cadence, calories: l.calories, trigger: l.lap_trigger,
  }));
}

const js = `// AUTO-GENERATED by scripts/gen-demo-data.js from the current database (ActivityLog2 real test data).
// No-backend fallback so the static preview shows the same data as the live backend.
// To regenerate after (re)seeding: node scripts/gen-demo-data.js
export const activities = ${JSON.stringify(activities, null, 2)};

export const sports = ${JSON.stringify(sports)};

const RECS = ${JSON.stringify(recsBy)};
const LAPS = ${JSON.stringify(lapsBy)};

export function detail(id) {
  const a = activities.find((x) => x.id === Number(id)) || activities[0];
  return { activity: a, records: RECS[a.id] || [], laps: LAPS[a.id] || [] };
}

function agg() {
  const totals = {};
  const monthly = {};
  let count = 0, distance = 0, hours = 0, first = null, last = null;
  for (const a of activities) {
    count++; distance += a.distance_km || 0; const h = (a.duration_s || 0) / 3600; hours += h;
    if (!first || a.start_time < first) first = a.start_time;
    if (!last || a.start_time > last) last = a.start_time;
    const t = totals[a.sport] || (totals[a.sport] = { sport: a.sport, count: 0, distance_km: 0, hours: 0 });
    t.count++; t.distance_km += a.distance_km || 0; t.hours += h;
    const m = a.start_time.slice(0, 7);
    const mk = m + '|' + a.sport;
    const mo = monthly[mk] || (monthly[mk] = { month: m, sport: a.sport, distance_km: 0, hours: 0, count: 0 });
    mo.distance_km += a.distance_km || 0; mo.hours += h; mo.count++;
  }
  return {
    totals: Object.values(totals).map((x) => ({ ...x, distance_km: +x.distance_km.toFixed(1), hours: +x.hours.toFixed(1) })),
    monthly: Object.values(monthly).map((x) => ({ ...x, distance_km: +x.distance_km.toFixed(1), hours: +x.hours.toFixed(1) })),
    grand: { count, distance_km: +distance.toFixed(1), hours: +hours.toFixed(1), first, last },
  };
}

export const reports = agg();

export const equipment = ${JSON.stringify(equipment, null, 2)};

export function filteredActivities(f = {}) {
  let r = activities.filter((a) => !_removed.has(a.id));
  if (f.sport && f.sport !== 'all') r = r.filter((a) => a.sport === f.sport);
  if (f.from) r = r.filter((a) => a.start_time && a.start_time >= f.from);
  if (f.to) r = r.filter((a) => a.start_time && a.start_time <= f.to + 'T23:59:59.999Z');
  if (f.q) { const q = f.q.toLowerCase(); r = r.filter((a) => (a.name || '').toLowerCase().includes(q) || (a.source_file || '').toLowerCase().includes(q)); }
  return r.sort((a, b) => (b.start_time || '').localeCompare(a.start_time || ''));
}

let _removed = new Set();
export function removeActivity(id) { _removed.add(Number(id)); return { ok: true }; }
export function allRemoved() { return [..._removed]; }
`;

const outPath = path.join(__dirname, '..', 'client', 'lib', 'demoData.js');
fs.writeFileSync(outPath, js);
const kb = (fs.statSync(outPath).size / 1024).toFixed(1);
console.log('Wrote', outPath, '(' + kb + 'KB) with ' + activities.length + ' activities, ' + sports.join('/') + ', ' + equipment.length + ' devices.');
